// Capture the native Dart policy. Generate into a scratch directory and review;
// never regenerate an already-applied migration in place.
import 'dart:convert';
import 'dart:io';

import 'package:dourstuff/domain/query.dart';

void main(List<String> args) {
  if (args.length != 1 || !Platform.version.startsWith('3.13.5 ')) {
    throw StateError(
      'Use pinned Dart 3.13.5: export_tag_normalization.dart OUTPUT_DIRECTORY',
    );
  }
  final directory = Directory(args.single)..createSync(recursive: true);
  final lower = <List<int>>[];
  final trim = <int>[];
  final whitespace = <int>[];
  final regexp = RegExp(r'\s');
  final parity = <Map<String, Object>>[];
  final chunk = <int>[];
  void flush() {
    if (chunk.isEmpty) return;
    final input = String.fromCharCodes(chunk);
    parity.add({'input': input, 'normalized': normalized(input)});
    chunk.clear();
  }

  for (var cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    final value = String.fromCharCode(cp);
    final mapped = value.toLowerCase();
    if (value != mapped) {
      if (mapped.runes.length != 1) throw StateError('Not a scalar mapping');
      lower.add([cp, mapped.runes.single]);
    }
    if (value.trim().isEmpty) trim.add(cp);
    if (regexp.hasMatch(value)) whitespace.add(cp);
    // PostgreSQL text/JSONB cannot encode NUL. It remains an activation gap.
    if (cp != 0) chunk.add(cp);
    if (chunk.length == 4096) flush();
  }
  flush();
  for (final cp in {...trim, ...whitespace}) {
    final c = String.fromCharCode(cp);
    for (final input in [c, '${c}A${c}B$c', 'A$c$c', '${c}A']) {
      parity.add({'input': input, 'normalized': normalized(input)});
    }
  }
  for (final pair in lower) {
    final c = String.fromCharCode(pair[0]);
    final input = 'A$cΣİ\u0301$c Z';
    parity.add({'input': input, 'normalized': normalized(input)});
  }
  const encoder = JsonEncoder.withIndent('  ');
  void write(String name, String data) =>
      File('${directory.path}/$name').writeAsStringSync('$data\n');
  write(
    'tag-normalization-v1.json',
    jsonEncode({
      'policy': 'dart-native-3.13.5-v1',
      'lower': lower,
      'trim': trim,
      'whitespace': whitespace,
    }),
  );
  write('tag-normalization-parity.json', encoder.convert(parity));
  write(
    'tag_normalization_data.dart',
    '''// Generated by tool/export_tag_normalization.dart using native Dart 3.13.5.
// Frozen policy v1. SDK upgrades must not silently change persisted tag keys.
const tagLowercaseV1 = <int, int>{
${lower.map((p) => '  ${p[0]}: ${p[1]},').join('\n')}
};
const tagTrimV1 = <int>{${trim.join(', ')}};
const tagWhitespaceV1 = <int>{${whitespace.join(', ')}};
''',
  );
  String sqlChars(Iterable<int> codes) {
    final parts = codes
        .map(
          (c) => c <= 0xffff
              ? '\\${c.toRadixString(16).padLeft(4, '0')}'
              : '\\+${c.toRadixString(16).padLeft(6, '0')}',
        )
        .toList();
    return [
      for (var i = 0; i < parts.length; i += 32)
        "U&'${parts.skip(i).take(32).join()}'",
    ].join(' ||\n      ');
  }

  write(
    'tag_name_normalization.sql',
    '''-- Generated by tool/export_tag_normalization.dart using native Dart 3.13.5.
-- Frozen policy v1: explicit code points, no locale or Unicode normalization.
create function sync_private.clean_tag_name_v1(value text)
returns text language sql immutable strict parallel safe set search_path = '' as \$\$
  select regexp_replace(translate(btrim(value,
      ${sqlChars(trim)}),
      ${sqlChars(whitespace)},
      repeat(' ', ${whitespace.length})), ' +', ' ', 'g')
\$\$;

create function sync_private.normalized_tag_name_v1(value text)
returns text language sql immutable strict parallel safe set search_path = '' as \$\$
  select translate(sync_private.clean_tag_name_v1(value),
      ${sqlChars(lower.map((p) => p[0]))},
      ${sqlChars(lower.map((p) => p[1]))})
\$\$;
-- End generated normalization functions.
''',
  );
  stdout.writeln(
    'Exported ${lower.length} lowercase mappings, ${trim.length} trim and '
    '${whitespace.length} whitespace scalars; ${parity.length} parity cases.',
  );
}
